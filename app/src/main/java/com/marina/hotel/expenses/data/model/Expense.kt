package com.marina.hotel.expenses.data.model

import androidx.room.Entity
import androidx.room.PrimaryKey
import androidx.room.TypeConverters
import com.marina.hotel.expenses.data.db.converters.DateConverter
import kotlinx.serialization.Serializable
import java.util.Date

@Serializable
@Entity(tableName = "expenses")
data class Expense(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val expenseType: String,
    val expenseKind: String? = null,
    val relatedId: Long? = null,
    val description: String,
    val amount: Double,
    @TypeConverters(DateConverter::class) val date: Date = Date(),
    val cashTransactionId: Long? = null,
    val hotelDayKey: String? = null,
    val categoryUuid: String? = null,
    val cashFlowUuid: String? = null,
    val isAutoGenerated: Boolean = false,
    val employeeUuid: String? = null,
    val withdrawalUuid: String? = null,
    val employeeLinkCleared: Int = 0,
    val localUuid: String? = null,
    val serverId: Long? = null,
    val version: Int = 0,
    val origin: String = "local",
    val vectorClock: String? = null,
    val deviceId: String? = null,
    val idempotencyKey: String? = null,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
    val deletedAt: Long? = null,
    val isSynced: Boolean = false
) {
    companion object {
        const val SALARY_TYPE = "رواتب"
        const val SALARY_WITHDRAW = "سحب من الراتب"
        const val SALARY_DEDUCTION = "خصم من الراتب"
        const val SALARY_ADVANCE = "سلفة"

        val DEFAULT_EXPENSE_TYPES = listOf(
            SALARY_TYPE, "ديزل", "صيانة", "فواتير كهرباء ومياه",
            "مستلزمات", "مساعدة محتاج", "أغذية", "اخرى"
        )

        val SALARY_ACTIONS = listOf(SALARY_ADVANCE, SALARY_WITHDRAW, SALARY_DEDUCTION)
    }

    fun isSalaryExpense(): Boolean {
        return expenseType == SALARY_TYPE || expenseKind?.isNotEmpty() == true
    }

    fun getSalaryAction(): String? {
        return if (expenseType == SALARY_TYPE) {
            expenseKind
        } else null
    }
}

@Serializable
data class Employee(
    val id: Long,
    val name: String,
    val localUuid: String? = null,
    val serverId: Long? = null,
    val version: Int = 0,
    val origin: String = "local",
    val vectorClock: String? = null,
    val deviceId: String? = null,
    val idempotencyKey: String? = null,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
    val deletedAt: Long? = null,
    val isSynced: Boolean = false,
    val status: String = "active"
)