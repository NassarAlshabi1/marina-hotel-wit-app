// Parity unification: unit tests for the closed `expense_kind` wire
// contract shared with branch3 (Android/Kotlin + Cloudflare Worker).
//
// These mirror `worker/test/expense-kind.test.ts` so a legacy Flutter
// client and an explicit-kind Android client produce the same kind on
// the server.
//
// NOTE: This file is a pure-Dart unit test (no Flutter bindings, no
// Drift). It exercises only `lib/utils/expense_kind.dart`, so it can
// run without `flutter test` — `dart test` is sufficient. If the
// Flutter SDK is unavailable, run with `dart test test/services/expense_kind_test.dart`.

import 'package:flutter_test/flutter_test.dart';
import 'package:marina_hotel_mobile/utils/expense_kind.dart';

void main() {
  group('kExpenseKinds', () {
    test('contains the closed set shared with worker + Android', () {
      expect(kExpenseKinds, contains('normal'));
      expect(kExpenseKinds, contains('salary_advance'));
      expect(kExpenseKinds, contains('salary_installment'));
      expect(kExpenseKinds, contains('salary_withdrawal'));
      expect(kExpenseKinds, contains('salary_deduction'));
      expect(kExpenseKinds, contains('unclassified'));
      expect(kExpenseKinds.length, 6);
    });
  });

  group('legacyExpenseKind', () {
    test('سلفة → salary_advance', () {
      expect(
        legacyExpenseKind(
          expenseType: 'سلفة',
          isAutoGenerated: false,
          description: '',
        ),
        'salary_advance',
      );
    });

    test('رواتب / سحب راتب / سحب من الراتب → salary_withdrawal', () {
      for (final t in ['رواتب', 'سحب راتب', 'سحب من الراتب']) {
        expect(
          legacyExpenseKind(
            expenseType: t,
            isAutoGenerated: false,
            description: '',
          ),
          'salary_withdrawal',
          reason: 'type=$t',
        );
      }
    });

    test('خصم من الراتب (auto, contains قسط سلفة) → salary_installment', () {
      expect(
        legacyExpenseKind(
          expenseType: 'خصم من الراتب',
          isAutoGenerated: true,
          description: 'قسط سلفة شهر أكتوبر',
        ),
        'salary_installment',
      );
    });

    test('خصم من الراتب (auto, no قسط سلفة) → unclassified', () {
      expect(
        legacyExpenseKind(
          expenseType: 'خصم من الراتب',
          isAutoGenerated: true,
          description: 'edited historical note',
        ),
        'unclassified',
      );
    });

    test('خصم من الراتب (manual) → salary_deduction', () {
      expect(
        legacyExpenseKind(
          expenseType: 'خصم من الراتب',
          isAutoGenerated: false,
          description: 'قسط سلفة',
        ),
        'salary_deduction',
      );
    });

    test('خصم / خصم راتب / غياب → salary_deduction', () {
      for (final t in ['خصم', 'خصم راتب', 'غياب']) {
        expect(
          legacyExpenseKind(
            expenseType: t,
            isAutoGenerated: true,
            description: '',
          ),
          'salary_deduction',
          reason: 'type=$t',
        );
      }
    });

    test('مشتريات / unknown → normal', () {
      expect(
        legacyExpenseKind(
          expenseType: 'مشتريات',
          isAutoGenerated: false,
          description: '',
        ),
        'normal',
      );
    });
  });

  group('resolveExpenseKind', () {
    test('explicit valid kind wins regardless of legacy fields', () {
      expect(
        resolveExpenseKind(
          explicitKind: 'salary_deduction',
          expenseType: 'سلفة',
          isAutoGenerated: false,
          description: 'قسط سلفة',
        ),
        'salary_deduction',
      );
    });

    test('null explicit kind falls back to legacy classifier', () {
      expect(
        resolveExpenseKind(
          explicitKind: null,
          expenseType: 'سلفة',
          isAutoGenerated: false,
          description: '',
        ),
        'salary_advance',
      );
    });

    test('invalid explicit kind throws ArgumentError', () {
      expect(
        () => resolveExpenseKind(
          explicitKind: 'free text',
          expenseType: 'سلفة',
          isAutoGenerated: false,
          description: '',
        ),
        throwsArgumentError,
      );
    });
  });
}
