void main() {
  const mapper = PayloadMapper();

  group('roomToRemote', () {
    test('يُرسل الهوية وحقول المزامنة الأساسية', () {
      final payload = mapper.roomToRemote(_room());

      expect(payload['localUuid'], 'room-uuid-0001');
      expect(payload['roomNumber'], '101');
      expect(payload['type'], 'سويت');
      expect(payload['price'], 25000);
      expect(payload['status'], 'شاغرة');
      expect(payload['version'], 1);
      expect(payload['origin'], 'local');
      expect(payload['vectorClock'], '{"dev-a":3}');
      expect(payload['deviceId'], 'dev-a');
      // sync_origin محفوظة بالشرطة السفلية (داخل _preserveSnakeCase)
      expect(payload['sync_origin'], 'local');
    });

    test('لا يُرسل المعرّف المحلي autoIncrement أبداً', () {
      final payload = mapper.roomToRemote(_room());

      expect(payload.containsKey('id'), isFalse);
    });

    test('putIfStringNotEmpty: الحقول الفارغة/النل تُحذف وليس تُرسل فارغة', () {
      final payload = mapper.roomToRemote(_room());

      expect(payload.containsKey('imageUrl'), isFalse);
      expect(payload.containsKey('lastCleanedHotelDay'), isFalse);
      expect(payload.containsKey('idempotencyKey'), isFalse);
      expect(payload.containsKey('serverId'), isFalse);
      expect(payload.containsKey('deletedAt'), isFalse);
    });

    test('الحقول الاختيارية المعبأة تُرسل بقيمها', () {
      final payload = mapper.roomToRemote(
        _room(
          imageUrl: 'https://cdn.example/101.jpg',
          lastCleanedHotelDay: '2026-09-23',
          idempotencyKey: 'idem-1',
          requiresMaintenance: true,
        ),
      );

      expect(payload['imageUrl'], 'https://cdn.example/101.jpg');
      expect(payload['lastCleanedHotelDay'], '2026-09-23');
      expect(payload['idempotencyKey'], 'idem-1');
      expect(payload['requiresMaintenance'], isTrue);
    });
  });

  group('bookingToRemote', () {
    test('amount الموحّد يُشتق من totalDueCached (عقد الحقل الموحد)', () {
      final payload = mapper.bookingToRemote(_booking());

      expect(payload['amount'], 75000);
      expect(payload['totalDueCached'], 75000);
      expect(payload['totalPaidCached'], 30000);
      expect(payload['remainingBalanceCached'], 45000);
    });

    test('syncTimestamp يُشتق من lastModified (حتمية LWW)', () {
      final payload = mapper.bookingToRemote(_booking());

      expect(payload['syncTimestamp'], _t0);
    });

    test('checkoutDate/actualCheckout يُرسلان حتى لو null (مفتاح موجود)', () {
      final payload = mapper.bookingToRemote(_booking());

      expect(payload.containsKey('checkoutDate'), isTrue);
      expect(payload['checkoutDate'], isNull);
      expect(payload.containsKey('actualCheckout'), isTrue);
    });

    test('حقول ISO النل تُحذف ولا تلوث الحمولة', () {
      final payload = mapper.bookingToRemote(_booking());

      expect(payload.containsKey('createdAtIso'), isFalse);
      expect(payload.containsKey('updatedAtIso'), isFalse);
      expect(payload.containsKey('deletedAtIso'), isFalse);
      expect(payload.containsKey('notes'), isFalse);
      expect(payload.containsKey('financialFrozenAt'), isFalse);
    });
  });

  group('expenseToRemote', () {
    test(
      'isAutoGenerated يُرسل دائماً كـ boolean — حتى false (إصلاح P1-5)',
      () {
        final payload = mapper.expenseToRemote(
          _expense(isAutoGenerated: false),
        );

        expect(payload.containsKey('isAutoGenerated'), isTrue);
        expect(payload['isAutoGenerated'], isFalse);
      },
    );

    test('employeeUuid الفارغ يُحذف والمعبأ يُرسل', () {
      final empty = mapper.expenseToRemote(_expense(employeeUuid: null));
      final filled = mapper.expenseToRemote(
        _expense(employeeUuid: 'employee-uuid-0001'),
      );

      expect(empty.containsKey('employeeUuid'), isFalse);
      expect(filled['employeeUuid'], 'employee-uuid-0001');
    });

    test('حقول الهوية والمزامنة موجودة', () {
      final payload = mapper.expenseToRemote(_expense());

      expect(payload['localUuid'], 'expense-uuid-0001');
      expect(payload['amount'], 5000);
      expect(payload['hotelDayKey'], '2026-09-23');
      expect(payload.containsKey('syncTimestamp'), isTrue);
      expect(payload['deviceId'], 'dev-a');
    });
  });

  group('employeeToRemote', () {
    test('salary مرآة إلزامية لـ basicSalary (مطلوب من Secondary)', () {
      final payload = mapper.employeeToRemote(_employee());

      expect(payload['basicSalary'], 120000);
      expect(payload['salary'], 120000);
    });

    test('EmployeeID يُرسل بالتسمية المعتمدة في مخطط Appwrite', () {
      final payload = mapper.employeeToRemote(_employee());

      expect(payload['EmployeeID'], 'EMP-77');
      expect(payload.containsKey('employeeID'), isFalse);
    });

    test('حقول الإنهاء النل تُحذف', () {
      final payload = mapper.employeeToRemote(_employee());

      expect(payload.containsKey('terminationDate'), isFalse);
      expect(payload.containsKey('terminationReason'), isFalse);
      expect(payload.containsKey('deletedAt'), isFalse);
    });

    test('sanitizePayload يمنع أي حقل خارج مخطط employees', () {
      final payload = mapper.employeeToRemote(_employee());
      const allowed = {
        'localUuid',
        'serverId',
        'createdAt',
        'updatedAt',
        'deletedAt',
        'lastModified',
        'createdAtIso',
        'updatedAtIso',
        'deletedAtIso',
        'createdAtEpoch',
        'lastModifiedEpoch',
        'version',
        'origin',
        'vectorClock',
        'deviceId',
        'idempotencyKey',
        'syncTimestamp',
        'sync_origin',
        'name',
        'basicSalary',
        'salary',
        'position',
        'phone',
        'hireDate',
        'status',
        'terminationDate',
        'terminationReason',
        'EmployeeID',
      };

      expect(payload.keys.every(allowed.contains), isTrue);
    });
  });

  group('guestInfoToRemote', () {
    test('بيانات الهوية الأساسية تُرسل كاملة', () {
      final payload = mapper.guestInfoToRemote(_guestInfo());

      expect(payload['localUuid'], 'guestinfo-uuid-0001');
      expect(payload['roomNumber'], '101');
      expect(payload['guestName'], 'أحمد صالح');
      expect(payload['nationality'], 'يمني');
      expect(payload['idNumber'], '12345');
      expect(payload['idType'], 'بطاقة شخصية');
      expect(payload['deviceId'], 'dev-a');
    });

    test('guestPhone محلي فقط ولا يخرج للسحابة من هذا المحوّل', () {
      final payload = mapper.guestInfoToRemote(_guestInfo());

      expect(payload.containsKey('guestPhone'), isFalse);
    });

    test('الحقول الاختيارية النل/الفارغة تُحذف', () {
      final payload = mapper.guestInfoToRemote(_guestInfo());

      expect(payload.containsKey('issueDate'), isFalse);
      expect(payload.containsKey('issuePlace'), isFalse);
      expect(payload.containsKey('governorate'), isFalse);
      expect(payload.containsKey('notes'), isFalse);
    });

    test('الحقول الاختيارية المعبأة تُرسل', () {
      final payload = mapper.guestInfoToRemote(
        _guestInfo(governorate: 'عدن', notes: 'نزيل متكرر'),
      );

      expect(payload['governorate'], 'عدن');
      expect(payload['notes'], 'نزيل متكرر');
    });
  });

  group('paymentVoidToRemote', () {
    test('حقول الإلغاء الأساسية تُرسل كاملة', () {
      final payload = mapper.paymentVoidToRemote(_paymentVoid());

      expect(payload['localUuid'], 'void-uuid-0001');
      expect(payload['originalPaymentUuid'], 'payment-uuid-0001');
      // originalPaymentId معرف محلي لكنه حقل عمل داخل جدول payment_voids
      // (مرجع تدقيقي فقط — الربط عبر originalPaymentUuid/bookingUuid)
      expect(payload['originalPaymentId'], 44);
      expect(payload['bookingUuid'], 'booking-uuid-0001');
      expect(payload['voidedAmount'], 15000);
      expect(payload['voidReason'], 'خطأ إدخال');
      expect(payload['voidedBy'], 'manager-1');
      expect(payload['voidedAt'], _t0);
      expect(payload['hotelDayKey'], '2026-09-24');
    });

    test('الحقول v2 الاختيارية النل تُحذف', () {
      final payload = mapper.paymentVoidToRemote(_paymentVoid());

      expect(payload.containsKey('reversalPaymentUuid'), isFalse);
      expect(payload.containsKey('approvedBy'), isFalse);
      expect(payload.containsKey('note'), isFalse);
      expect(payload.containsKey('originalAmount'), isFalse);
      expect(payload.containsKey('paymentUuid'), isFalse);
    });

    test('الحقول v2 المعبأة تُرسل بقيمها الصحيحة', () {
      final payload = mapper.paymentVoidToRemote(
        _paymentVoid(originalAmount: 20000, note: 'إلغاء جزئي معتمد'),
      );

      expect(payload['originalAmount'], 20000);
      expect(payload['note'], 'إلغاء جزئي معتمد');
    });
  });
}
