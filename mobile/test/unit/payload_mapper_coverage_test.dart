// ============================================================================
//  PayloadMapper — Contract Unit Tests (coverage expansion)
// ============================================================================
//  اختبارات عقود التحويل إلى حمولات السحابة (lib/services/sync/
//  payload_mapper.dart) للكيانات التي لم تكن مغطاة سابقاً:
//    roomToRemote / bookingToRemote / expenseToRemote / employeeToRemote /
//    guestInfoToRemote / paymentVoidToRemote
//
//  ما تحرسه هذه الاختبارات (بترتيب الأهمية):
//    1. الهوية: localUuid يُرسل دائماً (مفتاح الترابط عبر الأجهزة).
//    2. سلامة الربط: لا يُرسل أبداً معرف محلي autoIncrement للسيرفر.
//    3. الساعة المتجهة والجهاز: vectorClock/deviceId موجودان دائماً.
//    4. دلالات putIfNotNull / putIfStringNotEmpty (غياب الفارغ/النل).
//    5. تطبيع bookingUuidCache للصيغة القياسية بالشرطات.
//    6. syncTimestamp = lastModified (حتمية الـ LWW).
//    7. تصفية sanitizePayload: لا يخرج أي حقل خارج مخطط Appwrite.
// ============================================================================

