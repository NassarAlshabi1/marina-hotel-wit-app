          db,
          localUuid: 'exp-clean-mirror',
          expenseType: 'سحب راتب',
          amount: 300,
          date: '2026-11-03',
        );
        await db
            .into(db.salaryWithdrawals)
            .insert(
              SalaryWithdrawalsCompanion.insert(
                localUuid: 'sw-clean-1',
                createdAt: _now,
                updatedAt: _now,
                lastModified: _now,
                employeeId: empId,
                amount: 300,
                withdrawDate: '2026-11-03',
                expenseId: d.Value(expId),
                expenseUuid: const d.Value('exp-clean-mirror'),
              ),
            );

        await db.customStatement(
          'DROP INDEX IF EXISTS ux_salary_withdrawals_expense_uuid_active',
        );
        // مسار onUpgrade: لا تكرارات ⇒ يُنشأ الفريد
        final duplicates = await db
            .customSelect(_migration75MirrorDuplicatesSql)
            .get();
        expect(duplicates, isEmpty);
        await db.customStatement(_migration75CreateUxSql);

        expect(
          await _indexExists(db, 'ux_salary_withdrawals_expense_uuid_active'),
          isTrue,
        );
        // وقيده يعمل فعلياً: ثانية نشطة بنفس expense_uuid تُرفض
        await expectLater(
          db
              .into(db.salaryWithdrawals)
              .insert(
                SalaryWithdrawalsCompanion.insert(
                  localUuid: 'sw-clean-2',
                  createdAt: _now,
                  updatedAt: _now,
                  lastModified: _now,
                  employeeId: empId,
                  amount: 300,
                  withdrawDate: '2026-11-03',
                  expenseId: d.Value(expId),
                  expenseUuid: const d.Value('exp-clean-mirror'),
                ),
              ),
          throwsA(anything),
        );
      },
    );
  });
}

// ── مصدر الحقيقة: نفس عبارات SQL المستخدمة في onUpgrade (from < 75) ──

/// استعلام التكرارات النشطة على رابط المرآة
const String _migration75MirrorDuplicatesSql =
    "SELECT expense_uuid, COUNT(*) AS c "
    'FROM salary_withdrawals '
    "WHERE expense_uuid IS NOT NULL AND TRIM(expense_uuid) != '' "
    'AND deleted_at IS NULL '
    'GROUP BY expense_uuid HAVING COUNT(*) > 1';

/// إنشاء الفريد الجزئي عند خلوّ البيانات من التكرارات
const String _migration75CreateUxSql =
    'CREATE UNIQUE INDEX IF NOT EXISTS '
    'ux_salary_withdrawals_expense_uuid_active '
    'ON salary_withdrawals (expense_uuid) '
    "WHERE expense_uuid IS NOT NULL AND TRIM(expense_uuid) != '' "
    'AND deleted_at IS NULL';

/// البديل العادي عند وجود تكرارات تاريخية (بلا فرض فريد ولا حذف)
const String _migration75CreatePlainIdxSql =
    'CREATE INDEX IF NOT EXISTS idx_salary_withdrawals_expense_uuid '
    'ON salary_withdrawals (expense_uuid)';
