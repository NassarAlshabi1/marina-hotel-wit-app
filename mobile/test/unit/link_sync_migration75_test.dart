const _now = 1760000000; // epoch ثابت للاختبار

AppDatabase _db() => AppDatabase.forTesting(NativeDatabase.memory());

Future<int> _insertExpense(
  AppDatabase db, {
  required String localUuid,
  required String expenseType,
  required double amount,
  required String date,
  bool isAutoGenerated = false,
  String? employeeUuid,
  String? hotelDayKey,
}) {
  return db
      .into(db.expenses)
      .insert(
        ExpensesCompanion.insert(
          localUuid: localUuid,
          createdAt: _now,
          updatedAt: _now,
          lastModified: _now,
          expenseType: expenseType,
          description: 'اختبار ترحيل 75',
          amount: amount,
          date: date,
          isAutoGenerated: d.Value(isAutoGenerated),
          employeeUuid: d.Value(employeeUuid),
          hotelDayKey: d.Value(hotelDayKey),
        ),
      );
}

/// نفس عبارات backfill التصنيف التي ينفذها onUpgrade (from < 75) —
/// من [kExpenseKindBackfillRules] ثم الحدّ الختامي general.
Future<void> _runMigration75KindBackfill(AppDatabase db) async {
  for (final (kind, condition) in kExpenseKindBackfillRules) {
    await db.customStatement(
      'UPDATE expenses SET expense_kind = ? '
      'WHERE expense_kind IS NULL AND $condition',
      [kind],
    );
  }
  await db.customStatement(kExpenseKindGeneralFallbackSql);
}

Future<void> _runUuidLinkIndexStatements(AppDatabase db) async {
  for (final ddl in kUuidLinkIndexStatements) {
    await db.customStatement(ddl);
  }
}

Future<bool> _indexExists(AppDatabase db, String name) async {
  final row =
      await db
          .customSelect(
            "SELECT COUNT(*) AS c FROM sqlite_master "
            "WHERE type = 'index' AND name = ?",
            variables: [d.Variable(name)],
          )
          .getSingle();
  return (row.data['c'] as int? ?? 0) > 0;
}

Future<Map<String, Object?>> _expenseRow(AppDatabase db, int id) async {
  final row =
      await db
          .customSelect(
            'SELECT * FROM expenses WHERE id = ?',
            variables: [d.Variable(id)],
          )
          .getSingle();
  return row.data;
}

