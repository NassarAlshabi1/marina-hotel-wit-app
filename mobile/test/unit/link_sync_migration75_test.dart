const _now = 1760000000; // epoch ثابت للاختبار

AppDatabase _db() => AppDatabase.forTesting(NativeDatabase.memory());

Future<int> _insertExpense(
  AppDatabase db, {
  required String localUuid,
  required String expenseType,
  required double amount,
  required String date,
  bool isAutoGenerated = false,
  String? employeeUuid,
  String? hotelDayKey,
}) {
  return db
      .into(db.expenses)
      .insert(
        ExpensesCompanion.insert(
          localUuid: localUuid,
          createdAt: _now,
          updatedAt: _now,
          lastModified: _now,
          expenseType: expenseType,
          description: 'اختبار ترحيل 75/76',
          amount: amount,
          date: date,
          isAutoGenerated: d.Value(isAutoGenerated),
          employeeUuid: d.Value(employeeUuid),
          hotelDayKey: d.Value(hotelDayKey),
        ),
      );
}

Future<void> _runUuidLinkIndexStatements(AppDatabase db) async {
  for (final ddl in kUuidLinkIndexStatements) {
    await db.customStatement(ddl);
  }
}

Future<bool> _indexExists(AppDatabase db, String name) async {
  final row = await db
      .customSelect(
        "SELECT COUNT(*) AS c FROM sqlite_master "
        "WHERE type = 'index' AND name = ?",
        variables: [d.Variable(name)],
      )
      .getSingle();
  return (row.data['c'] as int? ?? 0) > 0;
}

Future<bool> _columnExists(AppDatabase db, String column) async {
  final row = await db
      .customSelect(
        "SELECT COUNT(*) AS c FROM pragma_table_info('expenses') "
        'WHERE name = ?',
        variables: [d.Variable(column)],
      )
      .getSingle();
  return (row.data['c'] as int? ?? 0) > 0;
}

/// محاكاة جهاز سبق له تشغيل الترحيل 75 القديم: إضافة العمود والفهرس
/// اليدوياً ثم تنفيذ صيغ التنظيف نفسها التي ينفذها onUpgrade (from < 76).
Future<void> _simulateLegacy75ThenCleanup(AppDatabase db) async {
  await db.customStatement('ALTER TABLE expenses ADD COLUMN expense_kind TEXT');
  await db.customStatement(
    'CREATE INDEX IF NOT EXISTS idx_exp_kind_day '
    'ON expenses (expense_kind, hotel_day_key)',
  );
  expect(await _columnExists(db, 'expense_kind'), isTrue);
  expect(await _indexExists(db, 'idx_exp_kind_day'), isTrue);

  // نفس عبارات onUpgrade (from < 76) — الترتيب والفحص مطابقان
  final kindCol = await db
      .customSelect(
        "SELECT COUNT(*) AS c FROM pragma_table_info('expenses') "
        "WHERE name = 'expense_kind'",
      )
      .getSingle();
  if ((kindCol.data['c'] as int? ?? 0) > 0) {
    for (final ddl in kExpenseKindCleanupStatements) {
      try {
        await db.customStatement(ddl);
      } catch (_) {
        // DROP COLUMN قد يفشل على SQLite قديمة — نفس تسامح الترحيل
      }
    }
  }
}

