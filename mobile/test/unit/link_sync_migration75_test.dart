                localUuid: uuid,
                createdAt: _now,
                updatedAt: _now,
                lastModified: _now,
                employeeId: empId,
                amount: 300,
                withdrawDate: '2026-11-03',
                expenseId: d.Value(expId),
                expenseUuid: const d.Value('exp-dup-mirror'),
              ),
            );
        await sw('sw-dup-1');
        await sw('sw-dup-2');

        // محاكاة حارس onUpgrade (from < 75) — نفس عبارات SQL
        final uxRow = await db
            .customSelect(
              "SELECT COUNT(*) AS c FROM sqlite_master "
              "WHERE type = 'index' "
              "AND name = 'ux_salary_withdrawals_expense_uuid_active'",
            )
            .getSingle();
        if ((uxRow.data['c'] as int? ?? 0) == 0) {
          final duplicates = await db
              .customSelect(_migration75MirrorDuplicatesSql)
              .get();
          expect(duplicates, isNotEmpty);
          // مسار التكرارات: فهرس عادي + تقرير — لا فرض فريد ولا حذف
          await db.customStatement(_migration75CreatePlainIdxSql);
        }

        // التكراران بقيا — لا حذف تلقائي (§4.1/§1.3-1)
        final rows = await db
            .customSelect(
              'SELECT local_uuid FROM salary_withdrawals '
              "WHERE expense_uuid = 'exp-dup-mirror' "
              'AND deleted_at IS NULL',
            )
            .get();
        expect(rows, hasLength(2));
        // والفريد غير مفروض
        expect(
          await _indexExists(db, 'ux_salary_withdrawals_expense_uuid_active'),
          isFalse,
        );
        // والبديل العادي موجود للبحث
        expect(
          await _indexExists(db, 'idx_salary_withdrawals_expense_uuid'),
          isTrue,
        );
      },
    );

    test(
      '9. حارس الفهرس الفريد يُنشئه عندما البيانات سليمة (لا تكرارات)',
      () async {
        final db = _db();
        addTearDown(db.close);

        // موظف موجود أولاً — employeeId FK مقيد (PRAGMA foreign_keys = ON)
        final empId = await db
            .into(db.employees)
            .insert(
              EmployeesCompanion.insert(
                localUuid: 'emp-75-clean',
                createdAt: _now,
                updatedAt: _now,
                lastModified: _now,
                name: 'موظف',
                basicSalary: 0,
                status: 'active',
              ),
            );
