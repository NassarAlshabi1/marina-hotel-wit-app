const _now = 1760000000;

AppDatabase _db() => TestDatabase.create();

Future<Employee> _insertEmployee(
  AppDatabase db, {
  required String localUuid,
  String name = 'موظف اختبار',
  double basicSalary = 1000,
  String hireDate = '2024-01-01',
}) async {
  await db
      .into(db.employees)
      .insert(
        EmployeesCompanion.insert(
          localUuid: localUuid,
          createdAt: _now,
          updatedAt: _now,
          lastModified: _now,
          name: name,
          basicSalary: basicSalary,
          status: 'active',
          hireDate: d.Value(hireDate),
        ),
      );
  return (db.select(
    db.employees,
  )..where((e) => e.localUuid.equals(localUuid))).getSingle();
}

Future<int> _insertExpense(
  AppDatabase db, {
  required String localUuid,
  required int employeeId,
  String? employeeUuid,
  required String expenseType,
  required double amount,
  String date = '2026-11-01',
  bool isAutoGenerated = false,
  String description = '',
}) {
  return db
      .into(db.expenses)
      .insert(
        ExpensesCompanion.insert(
          localUuid: localUuid,
          createdAt: _now,
          updatedAt: _now,
          lastModified: _now,
          expenseType: expenseType,
          description: description,
          amount: amount,
          date: date,
          relatedId: d.Value(employeeId),
          employeeUuid: d.Value(employeeUuid),
          isAutoGenerated: d.Value(isAutoGenerated),
        ),
      );
}

Future<int> _insertMirror(
  AppDatabase db, {
  required String localUuid,
  required int employeeId,
  String? employeeUuid,
  String? expenseId,
  String? expenseUuid,
  required double amount,
  String date = '2026-11-01',
  String? withdrawalType,
}) {
  return db
      .into(db.salaryWithdrawals)
      .insert(
        SalaryWithdrawalsCompanion.insert(
          localUuid: localUuid,
          createdAt: _now,
          updatedAt: _now,
          lastModified: _now,
          employeeId: employeeId,
          employeeUuid: d.Value(employeeUuid),
          amount: amount,
          withdrawDate: date,
          expenseId: expenseId == null
              ? const d.Value.absent()
              : d.Value(int.parse(expenseId)),
          expenseUuid: d.Value(expenseUuid),
          withdrawalType: d.Value(withdrawalType),
          reason: d.Value(expenseId != null ? 'exp_$expenseId' : null),
        ),
      );
}

