  group('Cloud Wins وحارس Tombstone (§7.5/§8.2)', () {
    test(
      '10. تعارض متزامن: السحابة تفوز وعمليات Outbox تُعلَّم superseded_by_cloud',
      () async {
        final db = _db();
        addTearDown(db.close);
        final outboxDao = OutboxDao(db);

        // تعديل محلي معلق في outbox لنفس السجل
        await outboxDao.merge(
          entity: 'expenses',
          op: 'update',
          localUuid: 'exp-conflict',
          payload: {'amount': 999},
          clientTs: _now,
        );

        final pull = SyncPullService(
          appwriteService: AppwriteService(), // لا شبكة في مسار التعارض
          database: db,
          outboxDao: outboxDao,
        );

        // نسختان متزامنتان: لكل جهاز مكوّن لا يملكه الآخر — concurrent
        final result = await pull.checkAndResolveConflict(
          {
            'amount': 555,
            'lastModified': 5000,
            'deviceId': 'devB',
            'vectorClock': '{"devB":2}',
          },
          5000,
          remoteUpdatedAtSec: 5000,
          localVectorClock: '{"devA":2}',
          entityName: 'expenses',
          localUuid: 'exp-conflict',
          localData: {'amount': 999, 'vectorClock': '{"devA":2}'},
        );

        // ✅ Cloud Wins: نسخة السحابة تُطبَّق دائماً
        expect(result.shouldApplyRemote, isTrue);

        // ✅ وعمليات Outbox المتعارضة عُلّمت superseded_by_cloud
        final op = await (db.select(
          db.outbox,
        )..where((o) => o.localUuid.equals('exp-conflict'))).getSingle();
        expect(op.processingStatus, 'superseded_by_cloud');
      },
    );

    test(
      '11. حارس Tombstone: Outbox قديم فوق tombstone سحابي يُعلَّم ولا يُرفع',
      () async {
        final db = _db();
        addTearDown(db.close);
        final emp = await _insertEmployee(db, localUuid: 'emp-tomb');
        final outboxDao = OutboxDao(db);
        final entryId = await outboxDao.merge(
          entity: 'employees',
          op: 'update',
          localUuid: emp.localUuid,
          payload: {'name': 'تعديل قديم'},
          clientTs: 1000, // أقدم من tombstone (2000)
        );

        // tombstone سحابي وصل بعد ذلك: origin=server + deletedAt
        await (db.update(
          db.employees,
        )..where((e) => e.id.equals(emp.id))).write(
          const EmployeesCompanion(
            deletedAt: d.Value(2000),
            lastModified: d.Value(2000),
            origin: d.Value('server'),
          ),
        );

        const guard = OutboxTombstoneGuard();
        final superseded = await guard.supersedeIfStaleOverCloudTombstone(
          db: db,
          entity: 'employees',
          localUuid: emp.localUuid,
          outboxRowId: entryId,
          clientTs: 1000,
        );

        expect(superseded, isTrue);
        final op = await (db.select(
          db.outbox,
        )..where((o) => o.id.equals(entryId))).getSingle();
        expect(op.processingStatus, 'superseded_by_cloud');
      },
    );

    test(
      '12. حارس Tombstone: تعديل محلي أحدث من tombstone يُسمح رفعه',
      () async {
        final db = _db();
        addTearDown(db.close);
        final emp = await _insertEmployee(db, localUuid: 'emp-tomb2');
        final outboxDao = OutboxDao(db);
        final entryId = await outboxDao.merge(
          entity: 'employees',
          op: 'update',
          localUuid: emp.localUuid,
          payload: {'name': 'إعادة تفعيل محلية'},
          clientTs: 3000, // أحدث من tombstone (2000)
        );
        await (db.update(
          db.employees,
        )..where((e) => e.id.equals(emp.id))).write(
          const EmployeesCompanion(
            deletedAt: d.Value(2000),
            lastModified: d.Value(2000),
            origin: d.Value('server'),
          ),
        );

        final superseded = await const OutboxTombstoneGuard()
            .supersedeIfStaleOverCloudTombstone(
              db: db,
              entity: 'employees',
              localUuid: emp.localUuid,
              outboxRowId: entryId,
              clientTs: 3000,
            );

        expect(superseded, isFalse); // قرار المستخدم المحلي الأخير
        final op = await (db.select(
          db.outbox,
        )..where((o) => o.id.equals(entryId))).getSingle();
        expect(op.processingStatus, 'pending');
      },
    );

    test('13. المصنّف: تسديد سلفة ليس سحباً ولا خصماً ولا سلفة جديدة', () {
      const type = 'تسديد سلفة';
      expect(SalaryExpenseClassifier.isLoanRepayment(type), isTrue);
      expect(SalaryExpenseClassifier.isSalaryCashOut(type), isFalse);
      expect(SalaryExpenseClassifier.isSalaryDeduction(type), isFalse);
      expect(SalaryExpenseClassifier.isAdvanceWithdrawal(type), isFalse);
      expect(SalaryExpenseClassifier.isSalaryRelated(type), isTrue);
      // والسلفة العادية تبقى سلفة
      expect(SalaryExpenseClassifier.isAdvanceWithdrawal('سلفة'), isTrue);
    });
  });
