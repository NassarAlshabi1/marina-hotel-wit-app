void main() {
  const mapper = PayloadMapper();

  test('bookingNoteToRemote يرسل الحقول الإلزامية', () {
    final data = mapper.bookingNoteToRemote(_note());
    expect(data['syncTimestamp'], isA<int>());
    expect(data['createdAtEpoch'], isNotNull);
    expect(data['lastModifiedEpoch'], isNotNull);
    expect(data.containsKey('createdAtIso'), isTrue);
    expect(data.containsKey('updatedAtIso'), isTrue);
    expect(data.containsKey('deletedAtIso'), isTrue);
  });

  test('bookingNightToRemote يرسل الحقول الإلزامية', () {
    final data = mapper.bookingNightToRemote(_night());
    expect(data['syncTimestamp'], isA<int>());
    expect(data['createdAtEpoch'], isNotNull);
    expect(data['lastModifiedEpoch'], isNotNull);
    expect(data.containsKey('createdAtIso'), isTrue);
    expect(data.containsKey('updatedAtIso'), isTrue);
    expect(data.containsKey('deletedAtIso'), isTrue);
  });

  test('cashTransactionToRemote يرسل الحقول الإلزامية', () {
    final data = mapper.cashTransactionToRemote(_tx());
    expect(data['syncTimestamp'], isA<int>());
    expect(data['createdAtEpoch'], isNotNull);
    expect(data['lastModifiedEpoch'], isNotNull);
    expect(data.containsKey('createdAtIso'), isTrue);
    expect(data.containsKey('updatedAtIso'), isTrue);
    expect(data.containsKey('deletedAtIso'), isTrue);
  });

  test('salaryCycleToRemote يرسل الحقول الإلزامية', () {
    final data = mapper.salaryCycleToRemote(_cycle());
    expect(data['syncTimestamp'], isA<int>());
    expect(data['createdAtEpoch'], isNotNull);
    expect(data['lastModifiedEpoch'], isNotNull);
    expect(data.containsKey('createdAtIso'), isTrue);
    expect(data.containsKey('updatedAtIso'), isTrue);
    expect(data.containsKey('deletedAtIso'), isTrue);
  });

  test('salaryPaymentToRemote يرسل الحقول الإلزامية', () {
    final data = mapper.salaryPaymentToRemote(_payment());
    expect(data['syncTimestamp'], isA<int>());
    expect(data['createdAtEpoch'], isNotNull);
    expect(data['lastModifiedEpoch'], isNotNull);
    expect(data.containsKey('createdAtIso'), isTrue);
    expect(data.containsKey('updatedAtIso'), isTrue);
    expect(data.containsKey('deletedAtIso'), isTrue);
  });

  // ═══════════════════════════════════════════════════════════════
  // ✅ (2026-11-03) اختبارات إزالة FK الرقمية المحلية من الرفع (P1):
  // المعرفات الرقمية (autoincrement) تختلف بين الأجهزة — رفعها كان يشوّه
  // مستند السحابة ويغذّي ping-pong الدمج (نفس عائلة إصلاح expenses
  // b04d9d50). الربط عبر الأجهزة بحقول *Uuid فقط، والسحب يحلّها عبر
  // الـ adapters (UUID أولاً ثم serverId — وليس id محلي للمصادر البعيدة).
  // ═══════════════════════════════════════════════════════════════

  test('bookingNoteToRemote لا يرفع bookingId الرقمي المحلي', () {
    final data = mapper.bookingNoteToRemote(_note());
    expect(
      data.containsKey('bookingId'),
      isFalse,
      reason:
          'bookingId رقم محلي يختلف بين الأجهزة — الربط عبر '
          'bookingUuidCache (يُثرى في مساري الرفع عبر _withBookingUuid)',
    );
  });

  test('salaryCycleToRemote لا يرفع employeeId ويرفع employeeUuid', () {
    final data = mapper.salaryCycleToRemote(_cycle());
    expect(
      data.containsKey('employeeId'),
      isFalse,
      reason: 'employeeId رقم محلي يختلف بين الأجهزة',
    );
    // صف بلا uuid في العمود → لا يُرسل الحقل (putIfStringNotEmpty)،
    // ومسارا الرفع يُثريانه من جدول الموظفين.
    expect(data.containsKey('employeeUuid'), isFalse);

    final withUuid = mapper.salaryCycleToRemote(
      _cycle(employeeUuid: 'emp-uuid-1'),
    );
    expect(withUuid['employeeUuid'], 'emp-uuid-1');
    expect(withUuid['employeeLocalUuid'], 'emp-uuid-1');
  });

  test('salaryPaymentToRemote لا يرفع cycleId ويرفع روابط UUID', () {
    final data = mapper.salaryPaymentToRemote(_payment());
    expect(
      data.containsKey('cycleId'),
      isFalse,
      reason: 'cycleId رقم محلي يختلف بين الأجهزة',
    );
    expect(data.containsKey('cycleLocalUuid'), isFalse);

    final withUuid = mapper.salaryPaymentToRemote(
      _payment(cycleUuid: 'cycle-uuid-1', employeeUuid: 'emp-uuid-2'),
    );
    expect(withUuid['cycleLocalUuid'], 'cycle-uuid-1');
    expect(withUuid['employeeUuid'], 'emp-uuid-2');
  });

  test('salaryCarryOverLogToRemote لا يرفع employeeId ويرفع UUID', () {
    final data = mapper.salaryCarryOverLogToRemote(_carryLog());
    expect(
      data.containsKey('employeeId'),
      isFalse,
      reason: 'employeeId رقم محلي يختلف بين الأجهزة',
    );
    expect(data.containsKey('employeeUuid'), isFalse);

    final withUuid = mapper.salaryCarryOverLogToRemote(
      _carryLog(employeeUuid: 'emp-uuid-3'),
    );
    expect(withUuid['employeeUuid'], 'emp-uuid-3');
    expect(withUuid['employeeLocalUuid'], 'emp-uuid-3');
  });

  test('paymentToRemote يرسل هوية مستلم الدفعة كاملة', () {
    final data = mapper.paymentToRemote(_receiptPayment());

    expect(data['receivedByUserId'], 42);
    expect(data['receivedByName'], 'المستخدم 42');
    expect(data['receivedSessionUuid'], 'session-42');
    expect(data['receivedByCloudId'], 'cloud-user-42');
  });
}
