  static final Map<String, Map<String, String>> _phpToFlutter = {};

  static void _buildReverseMap() {
    if (_phpToFlutter.isNotEmpty) return;
    for (final entity in _flutterToPhp.keys) {
      _phpToFlutter[entity] = {};
      for (final entry in _flutterToPhp[entity]!.entries) {
        _phpToFlutter[entity]![entry.value] = entry.key;
      }
    }
  }

  static String toPhpField(String entity, String flutterField) {
    return _flutterToPhp[entity]?[flutterField] ?? _camelToSnake(flutterField);
  }

  static String toFlutterField(String entity, String phpField) {
    _buildReverseMap();
    return _phpToFlutter[entity]?[phpField] ?? _snakeToCamel(phpField);
  }

  static Map<String, dynamic> toPhpMap(
    String entity,
    Map<String, dynamic> flutterMap,
  ) {
    final result = <String, dynamic>{};
    for (final entry in flutterMap.entries) {
      final phpKey = toPhpField(entity, entry.key);
      result[phpKey] = _convertValueToPhp(entry.value);
    }
    return result;
  }

  static Map<String, dynamic> toFlutterMap(
    String entity,
    Map<String, dynamic> phpMap,
  ) {
    _buildReverseMap();
    final result = <String, dynamic>{};
    for (final entry in phpMap.entries) {
      final flutterKey = toFlutterField(entity, entry.key);
      result[flutterKey] = _convertValueToFlutter(entry.value);
    }
    return result;
  }

  static List<Map<String, dynamic>> toPhpList(
    String entity,
    List<Map<String, dynamic>> flutterList,
  ) {
    return flutterList.map((m) => toPhpMap(entity, m)).toList();
  }

  static List<Map<String, dynamic>> toFlutterList(
    String entity,
    List<dynamic> phpList,
  ) {
    return phpList
        .map((m) => toFlutterMap(entity, Map<String, dynamic>.from(m)))
        .toList();
  }

  static dynamic _convertValueToPhp(dynamic value) {
    if (value == null) return null;
    if (value is bool) return value ? 1 : 0;
    if (value is DateTime) return value.toIso8601String();
    if (value is List) return value.map(_convertValueToPhp).toList();
    if (value is Map) {
      return value.map((k, v) => MapEntry(k, _convertValueToPhp(v)));
    }
    return value;
  }

  static dynamic _convertValueToFlutter(dynamic value) {
    if (value == null) return null;
    if (value is int && (value == 0 || value == 1)) {
      return value;
    }
    if (value is String) {
      final dateRegex = RegExp(r'^\d{4}-\d{2}-\d{2}');
      if (dateRegex.hasMatch(value)) {
        try {
          return DateTime.parse(value);
        } catch (_) {
          return value;
        }
      }
    }
    if (value is List) return value.map(_convertValueToFlutter).toList();
    if (value is Map) {
      return value.map((k, v) => MapEntry(k, _convertValueToFlutter(v)));
    }
    return value;
  }

  static String _camelToSnake(String input) {
    return input.replaceAllMapped(
      RegExp(r'[A-Z]'),
      (match) => '_${match.group(0)!.toLowerCase()}',
    );
  }

  static String _snakeToCamel(String input) {
    return input.replaceAllMapped(
      RegExp(r'_([a-z])'),
      (match) => match.group(1)!.toUpperCase(),
    );
  }

  static List<String> getEntityFields(String entity) {
    return _flutterToPhp[entity]?.keys.toList() ?? [];
  }

  static List<String> getSupportedEntities() {
    return _flutterToPhp.keys.toList();
  }

  static bool isEntitySupported(String entity) {
    return _flutterToPhp.containsKey(entity);
  }

  static Map<String, dynamic> extractSyncFields(Map<String, dynamic> data) {
    const syncFields = [
      'localUuid',
      'serverId',
      'createdAt',
      'updatedAt',
      'deletedAt',
      'lastModified',
      'version',
      'origin',
      'vectorClock',
    ];
    return Map.fromEntries(
      data.entries.where((e) => syncFields.contains(e.key)),
    );
  }

  static Map<String, dynamic> excludeSyncFields(Map<String, dynamic> data) {
    const syncFields = [
      'localUuid',
      'serverId',
      'createdAt',
      'updatedAt',
      'deletedAt',
      'lastModified',
      'version',
      'origin',
      'vectorClock',
      'createdAtIso',
      'updatedAtIso',
      'deletedAtIso',
      'createdAtEpoch',
      'lastModifiedEpoch',
    ];
    return Map.fromEntries(
      data.entries.where((e) => !syncFields.contains(e.key)),
    );
  }

  static Map<String, dynamic> prepareForInsert(
    String entity,
    Map<String, dynamic> data, {
    bool includeId = false,
  }) {
    final phpData = toPhpMap(entity, data);
    if (!includeId) {
      phpData.remove('id');
    }
    phpData.remove('local_uuid');
    return phpData;
  }

  static Map<String, dynamic> prepareForUpdate(
    String entity,
    Map<String, dynamic> data,
  ) {
    final phpData = toPhpMap(entity, data);
    phpData.remove('id');
    phpData.remove('local_uuid');
    phpData.remove('created_at');
    phpData['updated_at'] = DateTime.now().toIso8601String();
    return phpData;
  }

