  static List<String> validateRequiredFields(
    String entity,
    Map<String, dynamic> phpData,
  ) {
    final required = _requiredFields[entity] ?? [];
    final missing = <String>[];
    for (final field in required) {
      if (!phpData.containsKey(field) || phpData[field] == null) {
        missing.add(field);
      }
    }
    return missing;
  }

