/// التصنيف الموحد لأنواع مصروفات الرواتب — العقد المحاسبي النقدي
///
/// «مصروفات الرواتب يجب أن تساوي استحقاقات الموظف» — الأساس:
/// كل حركة **نقدية** للموظف (سحب راتب / سلفة / دفع رواتب) تُسجَّل مصروفاً
/// وتُخصم من استحقاقه في آنٍ واحد، بينما الخصوم (غياب / خصم / خصم راتب /
/// أقساط السلفة) لا يخرج منها نقد — تُخصم من الاستحقاق فقط (شاشة
/// الاستحقاقات) فلا تدخل في مصروفات الرواتب إطلاقاً.
///
/// لماذا المطابقة التامة وليس `contains('راتب')`؟
/// - خدمة الاستحقاق SalaryEntitlementService تقرأ الأنواع بمطابقة تامة،
///   فالتقرير النقدي يطابق نفس الأنواع حرفياً لضمان تساوي المصروف مع
///   المخصوم من الاستحقاق.
/// - الـ wildcard القديم كان يوسّع التصنيف لسلوكيات غير مقصودة ويحسب
///   الخصوم غير النقدية مصروفات رواتب (مصروفات مضخمة).
///
/// ⚠️ هذا التصنيف مخصص لطبقة التقارير النقدية فقط. طبقة المزامنة لها
/// تصنيفها الأوسع الخاص بإقران السحوبات (`PayloadMapper.isSalaryExpenseType`)
/// ولا يجوز الخلط بينهما.
class SalaryExpenseClassification {
  SalaryExpenseClassification._();

  /// أنواع مصروفات الرواتب النقدية — خرج منها نقد فعلاً.
  ///
  /// مطابقة تامة بعد trim — نفس الأنواع التي تقرأها خدمة الاستحقاق
  /// كسحبيات (رواتب/سحب راتب/سحب من الراتب) وسلف (سلفة).
  static const List<String> cashSalaryTypes = [
    'رواتب',
    'سحب راتب',
    'سحب من الراتب',
    'سلفة',
  ];

  /// أنواع الخصوم غير النقدية — تُخصم من استحقاق الموظف فقط
  /// ولا تُحسب مصروفات رواتب (لا نقد خرج منها).
  ///
  /// يشمل أقساط السلفة المسجلة بنوع «خصم من الراتب» التلقائي — استبعادها
  /// هنا هو ما يمنع ازدواج السلفة (السلفة تُحسب مرة واحدة عند خروج النقد).
  static const List<String> nonCashDeductionTypes = [
    'خصم راتب',
    'خصم من الراتب',
    'خصم',
    'غياب',
  ];

  /// هل النوع مصروف رواتب نقدي (خرج منه نقد فعلاً)؟
  static bool isCashSalaryExpense(String type) =>
      cashSalaryTypes.contains(type.trim());

  /// هل النوع خصماً غير نقدي (يُخصم من الاستحقاق فقط، ليس مصروفاً نقدياً)؟
  static bool isNonCashDeduction(String type) =>
      nonCashDeductionTypes.contains(type.trim());
}
