import 'package:drift/drift.dart' as d;

import '../../utils/time.dart';
import '../local_db.dart';
import '../salary_expense_classifier.dart';

/// ✅ (2026-11-04 — وثيقة الربط والمزامنة الموحدة §16) مستودع التقارير
/// المالية للموظف — طبقة استعلام موحّدة UUID-first.
///
/// العقد (§16.1):
/// - مفتاح التجميع والتصفية هو `employeeUuid` — لا `employeeId`/`relatedId`.
/// - ربط المصروف بمرآته عبر `expenseUuid` فقط — لا `reason LIKE 'exp_%'`
///   ولا مطابقة amount/date.
/// - ما لا يُحلّ UUID له يُعرض في «غير مرتبط» ولا يُنسب لموظف (§16.1).
/// - DTO عرض فقط (projection) — ليس جدولاً مالياً ولا مصدر حقيقة (§16.2).
///
/// قاعدة منع الازدواج (§16.3) لكل تقرير:
/// - حركة الصندوق/المصروفات: تُحتسب من `expenses` فقط — المرايا لا تُجمع.
/// - كشف مسحوبات الموظف: تُحتسب من `salary_withdrawals` فقط — المصروف
///   المرآة لا يُجمع مرتين (يُستخدم للربط/العرض فقط).
/// - كشف حساب الموظف: كل حركة من مصدرها المعتمد مرة واحدة.
class EmployeeFinancialReportRepository {
  EmployeeFinancialReportRepository(this._db);

  final AppDatabase _db;

  // ═══════════════════════════════════════════════════════════════
  // كشف حساب الموظف (§16.4-A)
  // ═══════════════════════════════════════════════════════════════

  /// كشف حساب الموظف لنطاق زمني [fromDate, toDate) — UUID إلزامي.
  ///
  /// يبني الحركات من مصادرها المعتمدة دون ازدواج:
  /// - مصروفات الرواتب للموظف (سحب/سلفة/خصم/تسديد) من `expenses`
  ///   عبر employeeUuid (fallback legacy محلي فقط للسجلات القديمة بلا
  ///   UUID عبر relatedId الموثوق محلياً — §2).
  /// - السحوبات المباشرة بلا مصروف من `salary_withdrawals`
  ///   (expenseUuid IS NULL أو غير مطابق لمصروف مقروء) — المرايا
  ///   المرتبطة بمصروف مقروء لا تُكرر (المصروف هو المصدر).
  /// - تسديد السلفة النقدي (مرآة سالبة بنوع تسديد سلفة بلا مصروف).
  Future<EmployeeAccountStatement> buildEmployeeAccountStatement({
    required String employeeUuid,
    DateTime? fromDate,
    DateTime? toDate,
  }) async {
    final uuid = employeeUuid.trim();
    assert(uuid.isNotEmpty, 'employeeUuid إلزامي لكشف الحساب (§16.4-A)');

    final fromIso = fromDate != null
        ? Time.safeIsoToDateString(fromDate.toIso8601String())
        : null;
    // النطاق نصف مفتوح [from, to) — §16.8: تجنب تكرار نهاية اليوم.
    final toIso = toDate != null
        ? Time.safeIsoToDateString(toDate.toIso8601String())
        : null;

    final movements = <EmployeeFinancialMovement>[];

    // ── 0) حل الموظف محلياً بالـ UUID (§16.1: التجميع UUID-first) ──
    final employeeRow =
        await (_db.select(_db.employees)
              ..where((e) => e.localUuid.equals(uuid))
              ..limit(1))
            .getSingleOrNull();

    if (employeeRow == null) {
      // موظف غير موجود محلياً: لا ننسب أي مصروف له — كشف فارغ + تحذير.
      return EmployeeAccountStatement(
        employeeUuid: uuid,
        employeeName: null,
        movements: const [],
        unresolved: const [
          'الموظف غير موجود محلياً — لا تُنسب له أي حركة (§16.1)',
        ],
        totalEntitlement: 0,
        totalWithdrawals: 0,
        totalAdvances: 0,
        totalDeductions: 0,
        totalRepayments: 0,
        repaymentsFromSalary: 0,
        repaymentsCash: 0,
        remainingSalary: 0,
        advanceBalance: 0,
        netFinancialPosition: 0,
      );
    }

    // ── 1) مصروفات الموظف (المصدر المعتمد لحركاته الراتبية) ──
    // employeeUuid أولاً؛ fallback legacy محلي فقط للسجلات القديمة بلا
    // UUID عبر relatedId الموثوق محلياً (§2 الوثيقة).
    final expRows =
        await (_db.select(_db.expenses)..where(
              (e) =>
                  e.deletedAt.isNull() &
                  (e.employeeUuid.equals(uuid) |
                      ((e.employeeUuid.isNull() | e.employeeUuid.equals('')) &
                          e.relatedId.equals(employeeRow.id))),
            ))
            .get();

    final readExpenseIds = expRows.map((e) => e.id).toSet();
    final readExpenseUuids = expRows
        .map((e) => e.localUuid.trim())
        .where((u) => u.isNotEmpty)
        .toSet();

    for (final expense in expRows) {
      if (!_inRange(expense.date, fromIso, toIso)) continue;
      final type = expense.expenseType.trim();
      final isRepayment = SalaryExpenseClassifier.isLoanRepayment(type);
      final isDeduction = SalaryExpenseClassifier.isSalaryDeduction(type);
      final isCashOut = SalaryExpenseClassifier.isSalaryCashOut(type);
      final installment =
          type.contains('خصم من الراتب') &&
          expense.isAutoGenerated &&
          expense.description.contains('قسط سلفة');

      String direction;
      String category;
      if (isRepayment) {
        direction = 'payment';
        category = 'تسديد سلفة من الراتب';
      } else if (installment) {
        direction = 'payment';
        category = 'قسط سلفة (تلقائي)';
      } else if (isDeduction) {
        direction = 'deduction';
        category = type;
      } else if (type.contains('سلفة')) {
        direction = 'withdrawal';
        category = 'سلفة';
      } else if (isCashOut) {
        direction = 'withdrawal';
        category = 'سحب راتب';
      } else {
        // مصروف غير راتبي مرتبط بالموظف — يظهر في الكشف كمصروف عام
        direction = 'expense';
        category = type;
      }

      movements.add(
        EmployeeFinancialMovement(
          movementUuid: expense.localUuid,
          employeeUuid: uuid,
          source: 'expense',
          expenseUuid: expense.localUuid,
          date: expense.date,
          category: category,
          description: expense.description,
          amount: expense.amount,
          direction: direction,
          isLinked: true,
        ),
      );
    }

    // ── 2) السحوبات المباشرة بلا مصروف مقابل (سحب مباشر/تسديد نقدي) ──
    final withdrawals =
        await (_db.select(_db.salaryWithdrawals)..where((w) {
              return w.deletedAt.isNull() &
                  (w.employeeUuid.equals(uuid) |
                      ((w.employeeUuid.isNull() | w.employeeUuid.equals('')) &
                          w.employeeId.equals(employeeRow.id)));
            }))
            .get();

    for (final w in withdrawals) {
      final expenseUuid = (w.expenseUuid ?? '').trim();
      // مرآة مصروف مقروء → المصروف هو المصدر — لا تُجمع مرتين (§16.3).
      final isMirrorOfReadExpense =
          expenseUuid.isNotEmpty && readExpenseUuids.contains(expenseUuid);
      if (isMirrorOfReadExpense) continue;
      if (w.expenseId != null &&
          w.expenseId! > 0 &&
          readExpenseIds.contains(w.expenseId)) {
        // رابط رقمي محلي لمصروف مقروء (تراثي) — المصروف المصدر.
        continue;
      }

      if (!_inRange(w.withdrawDate, fromIso, toIso)) continue;

      final isRepayment =
          w.amount < 0 &&
          SalaryExpenseClassifier.isLoanRepayment(w.withdrawalType);
      final isAdvance =
          w.amount > 0 &&
          SalaryExpenseClassifier.isAdvanceWithdrawal(w.withdrawalType);

      movements.add(
        EmployeeFinancialMovement(
          movementUuid: w.localUuid,
          employeeUuid: uuid,
          source: 'salary_withdrawal',
          expenseUuid: expenseUuid.isEmpty ? null : expenseUuid,
          date: w.withdrawDate,
          category: isRepayment
              ? 'تسديد سلفة نقدي'
              : isAdvance
              ? 'سلفة (مباشرة)'
              : 'سحب راتب (مباشر)',
          description: (w.description ?? w.reason ?? '').trim(),
          amount: w.amount.abs(),
          direction: isRepayment ? 'payment' : 'withdrawal',
          isLinked: false,
        ),
      );
    }

    // ── 3) الترتيب الثابت: التاريخ ثم UUID (§16.4-A) ──
    movements.sort((a, b) {
      final byDate = a.date.compareTo(b.date);
      if (byDate != 0) return byDate;
      return a.movementUuid.compareTo(b.movementUuid);
    });

    // ── 4) الإجماليات وفق معادلة المالك (2026-11-04) ──
    double withdrawalsTotal = 0, advancesTotal = 0, deductionsTotal = 0;
    double repayFromSalary = 0, repayCash = 0;
    for (final m in movements) {
      switch (m.direction) {
        case 'withdrawal':
          if (m.category == 'سلفة' || m.category == 'سلفة (مباشرة)') {
            advancesTotal += m.amount;
          } else {
            withdrawalsTotal += m.amount;
          }
          break;
        case 'deduction':
          deductionsTotal += m.amount;
          break;
        case 'payment':
          if (m.category == 'تسديد سلفة نقدي') {
            repayCash += m.amount;
          } else {
            repayFromSalary += m.amount;
          }
          break;
        default:
          break;
      }
    }

    final now = DateTime.now();
    DateTime hireDate;
    try {
      hireDate = employeeRow.hireDate.isNotEmpty
          ? DateTime.parse(employeeRow.hireDate)
          : now;
    } catch (_) {
      hireDate = now;
    }
    int months = (now.year - hireDate.year) * 12 + (now.month - hireDate.month);
    if (now.day < hireDate.day) months--;
    if (months < 0) months = 0;
    final totalEntitlement = months * employeeRow.basicSalary;

    final remaining =
        totalEntitlement - withdrawalsTotal - deductionsTotal - repayFromSalary;
    final advanceBal = advancesTotal - (repayFromSalary + repayCash);
    final net = remaining - advanceBal;

    return EmployeeAccountStatement(
      employeeUuid: uuid,
      employeeName: employeeRow.name,
      movements: movements,
      unresolved: const [],
      totalEntitlement: totalEntitlement,
      totalWithdrawals: withdrawalsTotal,
      totalAdvances: advancesTotal,
      totalDeductions: deductionsTotal,
      totalRepayments: repayFromSalary + repayCash,
      repaymentsFromSalary: repayFromSalary,
      repaymentsCash: repayCash,
      remainingSalary: remaining,
      advanceBalance: advanceBal,
      netFinancialPosition: net,
    );
  }

  bool _inRange(String dateIso, String? fromIso, String? toIso) {
    final day = Time.safeIsoToDateString(dateIso);
    if (fromIso != null && day.compareTo(fromIso) < 0) return false;
    if (toIso != null && day.compareTo(toIso) >= 0) return false;
    return true;
  }

  // ═══════════════════════════════════════════════════════════════
  // تقرير المطابقة/سلامة الرواتب (§16.4-E) — تشخيصي فقط بلا إصلاح
  // ═══════════════════════════════════════════════════════════════

  /// حالة الربط لكل زوج مصروف/مرآة عبر expenseUuid — يعرض الأدلة
  /// ولا يصلح شيئاً (§16.4-E/§11).
  Future<List<ExpenseMirrorMatchReport>> buildMirrorMatchReport({
    String? employeeUuid,
  }) async {
    final expenses = await (_db.select(
      _db.expenses,
    )..where((e) => e.deletedAt.isNull())).get();
    final mirrors = await (_db.select(
      _db.salaryWithdrawals,
    )..where((w) => w.deletedAt.isNull())).get();

    final mirrorsByExpenseUuid = <String, List<SalaryWithdrawal>>{};
    for (final w in mirrors) {
      final eu = (w.expenseUuid ?? '').trim();
      if (eu.isEmpty) continue;
      mirrorsByExpenseUuid.putIfAbsent(eu, () => []).add(w);
    }

    final reports = <ExpenseMirrorMatchReport>[];
    for (final e in expenses) {
      if (employeeUuid != null &&
          (e.employeeUuid ?? '').trim() != employeeUuid.trim()) {
        continue;
      }
      final type = e.expenseType.trim();
      if (!SalaryExpenseClassifier.isSalaryRelated(type)) continue;

      final eu = e.localUuid.trim();
      final group = mirrorsByExpenseUuid[eu] ?? const <SalaryWithdrawal>[];
      final active = group;

      MirrorMatchStatus status;
      if (active.isEmpty) {
        status = MirrorMatchStatus.missingMirror;
      } else if (active.length > 1) {
        status = MirrorMatchStatus.duplicateMirror;
      } else if ((active.first.employeeUuid ?? '').trim() !=
          (e.employeeUuid ?? '').trim()) {
        status = MirrorMatchStatus.employeeMismatch;
      } else {
        status = MirrorMatchStatus.matched;
      }

      reports.add(
        ExpenseMirrorMatchReport(
          expenseUuid: eu,
          expenseType: type,
          expenseAmount: e.amount,
          expenseEmployeeUuid: (e.employeeUuid ?? '').trim(),
          mirrorUuids: active.map((w) => w.localUuid).toList(),
          mirrorEmployeeUuids: active
              .map((w) => (w.employeeUuid ?? '').trim())
              .toList(),
          mirrorAmounts: active.map((w) => w.amount).toList(),
          activeMirrorCount: active.length,
          status: status,
        ),
      );
    }

    // المرايا اليتيمة (expenseUuid لا يقابل مصروفاً نشطاً)
    final expenseUuids = expenses.map((e) => e.localUuid.trim()).toSet();
    for (final w in mirrors) {
      final eu = (w.expenseUuid ?? '').trim();
      if (eu.isEmpty || expenseUuids.contains(eu)) continue;
      if (employeeUuid != null &&
          (w.employeeUuid ?? '').trim() != employeeUuid.trim()) {
        continue;
      }
      reports.add(
        ExpenseMirrorMatchReport(
          expenseUuid: eu,
          expenseType: null,
          expenseAmount: null,
          expenseEmployeeUuid: '',
          mirrorUuids: [w.localUuid],
          mirrorEmployeeUuids: [(w.employeeUuid ?? '').trim()],
          mirrorAmounts: [w.amount],
          activeMirrorCount: 1,
          status: MirrorMatchStatus.orphanMirror,
        ),
      );
    }

    return reports;
  }

  // ═══════════════════════════════════════════════════════════════
  // تقرير الرواتب حسب الفترة (§16.4-B)
  // ═══════════════════════════════════════════════════════════════

  /// تجميع `salary_cycles` حسب `employeeUuid` وفترة الدورة، وربط
  /// `salary_payments` بالدورة عبر `cycleUuid` أولاً ثم cycleId المحلي
  /// (cache محلي بعد حل UUID — §3.4/§16.4-B).
  ///
  /// السجلات غير المرتبطة (بلا employeeUuid أو لا يحل لموظف) تُعرض في
  /// [EmployeeSalaryCyclesReport.unresolved] ولا تُنسب لموظف (§16.1).
  Future<EmployeeSalaryCyclesReport> buildSalaryCyclesReport({
    String? employeeUuid,
    DateTime? fromDate,
    DateTime? toDate,
  }) async {
    final uuid = employeeUuid?.trim();
    final fromIso = fromDate != null
        ? Time.safeIsoToDateString(fromDate.toIso8601String())
        : null;
    final toIso = toDate != null
        ? Time.safeIsoToDateString(toDate.toIso8601String())
        : null;

    final cycles =
        await (_db.select(_db.salaryCycles)..where(
              (c) => uuid == null || uuid.isEmpty
                  ? const d.Constant(true)
                  : c.employeeUuid.equals(uuid),
            ))
            .get();
    final payments =
        await (_db.select(_db.salaryPayments)..where(
              (p) => uuid == null || uuid.isEmpty
                  ? const d.Constant(true)
                  : p.employeeUuid.equals(uuid),
            ))
            .get();
    final employees = await _db.select(_db.employees).get();
    final nameByUuid = {for (final e in employees) e.localUuid.trim(): e.name};

    final unresolved = <String>[];
    final rows = <SalaryCycleReportRow>[];

    // ربط الدفعات بالدورة: cycleUuid أولاً (هوية دائمة §3.4)، ثم
    // cycleId الرقمي كـ cache محلي بعد حل الدورة بالـ UUID.
    final paymentsByCycleUuid = <String, List<SalaryPayment>>{};
    final paymentsByCycleId = <int, List<SalaryPayment>>{};
    for (final p in payments) {
      final cu = (p.cycleUuid ?? '').trim();
      if (cu.isNotEmpty) {
        paymentsByCycleUuid.putIfAbsent(cu, () => []).add(p);
      }
      paymentsByCycleId.putIfAbsent(p.cycleId, () => []).add(p);
    }

    int totalExpected = 0, totalPaid = 0, totalRemaining = 0;
    for (final c in cycles) {
      final cUuid = c.localUuid.trim();
      // نطاق الدورة نصف مفتوح [from, to) على بداية الدورة الفندقية (§16.8).
      final day = (c.hotelDayStart ?? '').trim();
      if (fromIso != null && day.isNotEmpty && day.compareTo(fromIso) < 0) {
        continue;
      }
      if (toIso != null && day.isNotEmpty && day.compareTo(toIso) >= 0) {
        continue;
      }

      final empUuid = (c.employeeUuid ?? '').trim();
      final resolvedName = empUuid.isEmpty ? null : nameByUuid[empUuid];
      if (empUuid.isEmpty || resolvedName == null) {
        unresolved.add(
          'دورة راتب ${c.cycleKey} (uuid=$cUuid) بلا موظف محلول '
          '— لا تُنسب لموظف (§16.1)',
        );
        // §16.4-B/§16.1: السجل غير المرتبط في قسم منفصل — لا يدخل صفوف
        // التقرير ولا إجمالياته، ولا يُنسب لموظف غير مؤكد.
        continue;
      }

      final cyclePayments = <SalaryPayment>[
        ...?paymentsByCycleUuid[cUuid],
        ...(paymentsByCycleId[c.id] ?? const <SalaryPayment>[]).where(
          (p) => (p.cycleUuid ?? '').trim().isEmpty,
        ),
      ];

      totalExpected += c.expectedAmount;
      totalPaid += c.actualPaid;
      totalRemaining += c.remainingAmount;

      rows.add(
        SalaryCycleReportRow(
          cycleUuid: cUuid,
          cycleKey: c.cycleKey,
          employeeUuid: empUuid.isEmpty ? null : empUuid,
          employeeName: resolvedName,
          hotelDayStart: c.hotelDayStart,
          hotelDayEnd: c.hotelDayEnd,
          expectedAmount: c.expectedAmount.toDouble(),
          actualPaid: c.actualPaid.toDouble(),
          remainingAmount: c.remainingAmount.toDouble(),
          status: c.status,
          payments: cyclePayments
              .map(
                (p) => SalaryPaymentReportRow(
                  paymentUuid: p.localUuid,
                  amount: p.amount.toDouble(),
                  paymentDateIso: p.paymentDateIso,
                  method: p.method,
                  hotelDayKey: p.hotelDayKey,
                  linkedViaUuid: (p.cycleUuid ?? '').trim() == cUuid,
                ),
              )
              .toList(),
        ),
      );
    }

    rows.sort((a, b) {
      final byDay = (a.hotelDayStart ?? '').compareTo(b.hotelDayStart ?? '');
      if (byDay != 0) return byDay;
      return a.cycleUuid.compareTo(b.cycleUuid);
    });

    return EmployeeSalaryCyclesReport(
      cycles: rows,
      unresolved: unresolved,
      totalExpected: totalExpected.toDouble(),
      totalPaid: totalPaid.toDouble(),
      totalRemaining: totalRemaining.toDouble(),
    );
  }

  // ═══════════════════════════════════════════════════════════════
  // تقرير المصروفات حسب الموظف (§16.4-C)
  // ═══════════════════════════════════════════════════════════════

  /// المصدر `expenses` فقط — المرايا لا تُجمع (§16.3). التصنيف مشتق من
  /// `expenseType` عبر [SalaryExpenseClassifier] (قرار المالك 2026-11-04:
  /// لا عمود expense_kind — §3.2)، و`expenseType` نفسه للعرض/التوافق.
  /// المصروف بلا employeeUuid لا يظهر تحت موظف — يظهر في غير المرتبط.
  Future<EmployeeExpensesReport> buildExpensesByEmployeeReport({
    String? employeeUuid,
    DateTime? fromDate,
    DateTime? toDate,
    String? typeContains,
    bool salaryFamilyOnly = false,
  }) async {
    final uuid = employeeUuid?.trim();
    final fromIso = fromDate != null
        ? Time.safeIsoToDateString(fromDate.toIso8601String())
        : null;
    final toIso = toDate != null
        ? Time.safeIsoToDateString(toDate.toIso8601String())
        : null;

    final rows =
        await (_db.select(_db.expenses)..where((e) {
              d.Expression<bool> exp = e.deletedAt.isNull();
              if (uuid != null && uuid.isNotEmpty) {
                exp = exp & e.employeeUuid.equals(uuid);
              }
              return exp;
            }))
            .get();

    final linked = <EmployeeExpenseReportRow>[];
    final unlinked = <String>[];
    double total = 0;
    final byCategory = <String, double>{};

    for (final e in rows) {
      final type = e.expenseType.trim();
      if (typeContains != null &&
          typeContains.isNotEmpty &&
          !type.contains(typeContains)) {
        continue;
      }
      final isSalary = SalaryExpenseClassifier.isSalaryRelated(type);
      if (salaryFamilyOnly && !isSalary) continue;
      if (!_inRange(e.date, fromIso, toIso)) continue;

      final empUuid = (e.employeeUuid ?? '').trim();
      if (uuid == null || uuid.isEmpty) {
        // تقرير عام: كل مصروف راتبي بلا موظف محلول → غير مرتبط (§16.4-C).
        if (isSalary && empUuid.isEmpty) {
          unlinked.add(
            'مصروف راتبي بلا employeeUuid: ${e.localUuid} '
            '(مبلغ ${e.amount} — $type)',
          );
          continue;
        }
      }

      final category = isSalary
          ? SalaryExpenseClassifier.isLoanRepayment(type)
                ? 'تسديد سلفة'
                : SalaryExpenseClassifier.isSalaryDeduction(type)
                ? 'خصم'
                : SalaryExpenseClassifier.isAdvanceWithdrawal(type)
                ? 'سلفة'
                : 'سحب راتب'
          : type;

      total += e.amount;
      byCategory[category] = (byCategory[category] ?? 0) + e.amount;
      linked.add(
        EmployeeExpenseReportRow(
          expenseUuid: e.localUuid,
          employeeUuid: empUuid,
          date: e.date,
          hotelDayKey: e.hotelDayKey,
          type: type,
          category: category,
          description: e.description,
          amount: e.amount,
          isAutoGenerated: e.isAutoGenerated,
        ),
      );
    }

    linked.sort((a, b) {
      final byDate = a.date.compareTo(b.date);
      if (byDate != 0) return byDate;
      return a.expenseUuid.compareTo(b.expenseUuid);
    });

    return EmployeeExpensesReport(
      expenses: linked,
      unlinked: unlinked,
      total: total,
      totalsByCategory: byCategory,
    );
  }

  // ═══════════════════════════════════════════════════════════════
  // تقرير المسحوبات (§16.4-D)
  // ═══════════════════════════════════════════════════════════════

  /// المصدر `salary_withdrawals` فقط — مصروف المرآة لا يُجمع مرتين
  /// (§16.3). تمييز السحب المباشر (`expenseUuid` NULL أو غير محلول) عن
  /// سحب له مصروف مرآة عبر `expenseUuid` — لا `expenseId` وحده.
  Future<EmployeeWithdrawalsReport> buildWithdrawalsReport({
    String? employeeUuid,
    DateTime? fromDate,
    DateTime? toDate,
  }) async {
    final uuid = employeeUuid?.trim();
    final fromIso = fromDate != null
        ? Time.safeIsoToDateString(fromDate.toIso8601String())
        : null;
    final toIso = toDate != null
        ? Time.safeIsoToDateString(toDate.toIso8601String())
        : null;

    final rows =
        await (_db.select(_db.salaryWithdrawals)..where((w) {
              d.Expression<bool> exp = w.deletedAt.isNull();
              if (uuid != null && uuid.isNotEmpty) {
                exp = exp & w.employeeUuid.equals(uuid);
              }
              return exp;
            }))
            .get();

    final expenses = await (_db.select(
      _db.expenses,
    )..where((e) => e.deletedAt.isNull())).get();
    final expenseUuidSet = expenses
        .map((e) => e.localUuid.trim())
        .where((u) => u.isNotEmpty)
        .toSet();

    final direct = <EmployeeWithdrawalReportRow>[];
    final mirrors = <EmployeeWithdrawalReportRow>[];
    final unresolved = <String>[];
    double directTotal = 0, mirrorTotal = 0;

    for (final w in rows) {
      if (!_inRange(w.withdrawDate, fromIso, toIso)) continue;
      final empUuid = (w.employeeUuid ?? '').trim();
      if (empUuid.isEmpty) {
        unresolved.add(
          'مسحوب بلا employeeUuid: ${w.localUuid} '
          '(مبلغ ${w.amount}، ${w.withdrawDate})',
        );
        continue;
      }

      final eu = (w.expenseUuid ?? '').trim();
      final hasResolvableMirror = eu.isNotEmpty && expenseUuidSet.contains(eu);
      final row = EmployeeWithdrawalReportRow(
        withdrawalUuid: w.localUuid,
        employeeUuid: empUuid,
        expenseUuid: eu.isEmpty ? null : eu,
        date: w.withdrawDate,
        hotelDayKey: w.hotelDayKey,
        amount: w.amount,
        withdrawalType: w.withdrawalType ?? '',
        description: (w.description ?? w.reason ?? '').trim(),
        isMirrorOfExpense: hasResolvableMirror,
      );
      if (hasResolvableMirror) {
        mirrorTotal += w.amount;
        mirrors.add(row);
      } else {
        directTotal += w.amount;
        direct.add(row);
      }
    }

    direct.sort((a, b) {
      final byDate = a.date.compareTo(b.date);
      if (byDate != 0) return byDate;
      return a.withdrawalUuid.compareTo(b.withdrawalUuid);
    });
    mirrors.sort((a, b) {
      final byDate = a.date.compareTo(b.date);
      if (byDate != 0) return byDate;
      return a.withdrawalUuid.compareTo(b.withdrawalUuid);
    });

    return EmployeeWithdrawalsReport(
      directWithdrawals: direct,
      mirrorWithdrawals: mirrors,
      unresolved: unresolved,
      directTotal: directTotal,
      mirrorTotal: mirrorTotal,
    );
  }

  // ═══════════════════════════════════════════════════════════════
  // تقرير السجلات غير المرتبطة (§16.4-F)
  // ═══════════════════════════════════════════════════════════════

  /// يجمع كل السجلات المالية التي لا يحلّ UUID أبها — تُعرض أدلة فقط
  /// ولا تُنسب لموظف (§16.1/§16.4-F). لا يصلح شيئاً تلقائياً.
  Future<UnlinkedFinancialRecordsReport> buildUnlinkedRecordsReport() async {
    final employees = await _db.select(_db.employees).get();
    final employeeUuids = employees
        .map((e) => e.localUuid.trim())
        .where((u) => u.isNotEmpty)
        .toSet();

    final expenses = await (_db.select(
      _db.expenses,
    )..where((e) => e.deletedAt.isNull())).get();
    final withdrawals = await (_db.select(
      _db.salaryWithdrawals,
    )..where((w) => w.deletedAt.isNull())).get();
    final cycles = await (_db.select(
      _db.salaryCycles,
    )..where((c) => c.deletedAt.isNull())).get();
    final payments = await (_db.select(
      _db.salaryPayments,
    )..where((p) => p.deletedAt.isNull())).get();
    final carryOvers = await (_db.select(
      _db.salaryCarryOverLogs,
    )..where((c) => c.deletedAt.isNull())).get();

    final items = <UnlinkedRecordItem>[];
    final expenseUuidSet = expenses
        .map((e) => e.localUuid.trim())
        .where((u) => u.isNotEmpty)
        .toSet();

    for (final e in expenses) {
      final type = e.expenseType.trim();
      if (!SalaryExpenseClassifier.isSalaryRelated(type)) continue;
      final empUuid = (e.employeeUuid ?? '').trim();
      if (empUuid.isEmpty) {
        items.add(
          UnlinkedRecordItem(
            source: 'expense',
            recordUuid: e.localUuid,
            reason: 'مصروف راتبي بلا employeeUuid',
            amount: e.amount,
            date: e.date,
          ),
        );
      } else if (!employeeUuids.contains(empUuid)) {
        items.add(
          UnlinkedRecordItem(
            source: 'expense',
            recordUuid: e.localUuid,
            reason: 'employeeUuid لا يطابق موظفاً محلياً',
            amount: e.amount,
            date: e.date,
          ),
        );
      }
    }

    for (final w in withdrawals) {
      final empUuid = (w.employeeUuid ?? '').trim();
      if (empUuid.isEmpty) {
        items.add(
          UnlinkedRecordItem(
            source: 'salary_withdrawal',
            recordUuid: w.localUuid,
            reason: 'مسحوب بلا employeeUuid',
            amount: w.amount,
            date: w.withdrawDate,
          ),
        );
      } else if (!employeeUuids.contains(empUuid)) {
        items.add(
          UnlinkedRecordItem(
            source: 'salary_withdrawal',
            recordUuid: w.localUuid,
            reason: 'employeeUuid لا يطابق موظفاً محلياً',
            amount: w.amount,
            date: w.withdrawDate,
          ),
        );
      }
      final eu = (w.expenseUuid ?? '').trim();
      if (eu.isNotEmpty && !expenseUuidSet.contains(eu)) {
        items.add(
          UnlinkedRecordItem(
            source: 'salary_withdrawal',
            recordUuid: w.localUuid,
            reason: 'expenseUuid غير موجود في المصروفات النشطة (مرآة يتيمة)',
            amount: w.amount,
            date: w.withdrawDate,
          ),
        );
      }
    }

    for (final c in cycles) {
      final empUuid = (c.employeeUuid ?? '').trim();
      if (empUuid.isEmpty || !employeeUuids.contains(empUuid)) {
        items.add(
          UnlinkedRecordItem(
            source: 'salary_cycle',
            recordUuid: c.localUuid,
            reason: empUuid.isEmpty
                ? 'دورة بلا employeeUuid'
                : 'employeeUuid لا يطابق موظفاً محلياً',
            amount: c.expectedAmount.toDouble(),
            date: c.hotelDayStart ?? c.cycleKey,
          ),
        );
      }
    }
    for (final p in payments) {
      final empUuid = (p.employeeUuid ?? '').trim();
      if (empUuid.isEmpty || !employeeUuids.contains(empUuid)) {
        items.add(
          UnlinkedRecordItem(
            source: 'salary_payment',
            recordUuid: p.localUuid,
            reason: empUuid.isEmpty
                ? 'دفعة بلا employeeUuid'
                : 'employeeUuid لا يطابق موظفاً محلياً',
            amount: p.amount.toDouble(),
            date: p.paymentDateIso,
          ),
        );
      }
    }
    for (final c in carryOvers) {
      final empUuid = (c.employeeUuid ?? '').trim();
      if (empUuid.isEmpty || !employeeUuids.contains(empUuid)) {
        items.add(
          UnlinkedRecordItem(
            source: 'carry_over',
            recordUuid: c.localUuid,
            reason: empUuid.isEmpty
                ? 'Carry-over بلا employeeUuid'
                : 'employeeUuid لا يطابق موظفاً محلياً',
            amount: c.amount,
            date: c.carryDate ?? c.hotelDayKey ?? '',
          ),
        );
      }
    }

    // pending_links: السجلات التي وصل أبها متأخراً — عددها وأسبابها (§11).
    final pendingRows = await (_db.select(
      _db.pendingLinks,
    )..where((p) => p.resolvedAt.isNull())).get();
    final pendingItems = pendingRows
        .map(
          (p) => PendingLinkItem(
            entity: p.entity,
            recordUuid: p.localUuid,
            parentEntity: p.parentEntity,
            parentUuid: p.parentUuid,
            reason: p.reason,
            attempts: p.attempts,
            lastAttemptAt: p.lastAttemptAt,
          ),
        )
        .toList();

    return UnlinkedFinancialRecordsReport(
      items: items,
      pendingLinks: pendingItems,
    );
  }

  // ═══════════════════════════════════════════════════════════════
  // تقرير إجمالي الموظفين (§16.4-G)
  // ═══════════════════════════════════════════════════════════════

  /// تجميع حسب `employeeUuid` فقط — قواعد منع الازدزام §16.3:
  /// - كل مصروف راتبي يُحتسب مرة (من `expenses`) — مرآته لا تُجمع.
  /// - السحوبات المباشرة (بلا مصروف مقابل) من `salary_withdrawals`.
  /// - السجلات غير المحلولة في مجموعة مستقلة (§16.4-G).
  /// - مجموع التقرير = مجموع السجلات المصدرية بعد الاستبعاد + فروقات
  ///   موثقة في [EmployeeTotalsReport.reconciliation].
  Future<EmployeeTotalsReport> buildEmployeeTotalsReport() async {
    final employees = await _db.select(_db.employees).get();
    final nameByUuid = {for (final e in employees) e.localUuid.trim(): e.name};

    final expenses = await (_db.select(
      _db.expenses,
    )..where((e) => e.deletedAt.isNull())).get();
    final withdrawals = await (_db.select(
      _db.salaryWithdrawals,
    )..where((w) => w.deletedAt.isNull())).get();
    final expenseUuidSet = expenses
        .map((e) => e.localUuid.trim())
        .where((u) => u.isNotEmpty)
        .toSet();

    final perEmployee = <String, EmployeeTotalsRow>{};
    EmployeeTotalsRow rowFor(String uuid) => perEmployee.putIfAbsent(
      uuid,
      () =>
          EmployeeTotalsRow(employeeUuid: uuid, employeeName: nameByUuid[uuid]),
    );

    int movementsCount = 0;
    for (final e in expenses) {
      final type = e.expenseType.trim();
      if (!SalaryExpenseClassifier.isSalaryRelated(type)) continue;
      final empUuid = (e.employeeUuid ?? '').trim();
      if (empUuid.isEmpty || !nameByUuid.containsKey(empUuid)) continue;
      final row = rowFor(empUuid);
      row.movementsCount++;
      movementsCount++;
      if (SalaryExpenseClassifier.isLoanRepayment(type)) {
        row.repaymentsTotal += e.amount;
      } else if (SalaryExpenseClassifier.isSalaryDeduction(type)) {
        row.deductionsTotal += e.amount;
      } else if (SalaryExpenseClassifier.isAdvanceWithdrawal(type)) {
        row.advancesTotal += e.amount;
      } else {
        row.withdrawalsTotal += e.amount;
      }
    }

    for (final w in withdrawals) {
      final empUuid = (w.employeeUuid ?? '').trim();
      if (empUuid.isEmpty || !nameByUuid.containsKey(empUuid)) continue;
      final eu = (w.expenseUuid ?? '').trim();
      // مرآة مصروف مقروء → المصروف هو المصدر — لا تُجمع مرتين (§16.3).
      if (eu.isNotEmpty && expenseUuidSet.contains(eu)) continue;
      final row = rowFor(empUuid);
      row.movementsCount++;
      movementsCount++;
      if (w.amount < 0 &&
          SalaryExpenseClassifier.isLoanRepayment(w.withdrawalType)) {
        row.repaymentsTotal += w.amount.abs();
      } else if (w.amount > 0 &&
          SalaryExpenseClassifier.isAdvanceWithdrawal(w.withdrawalType)) {
        row.advancesTotal += w.amount;
      } else {
        row.withdrawalsTotal += w.amount;
      }
    }

    // الفروقات: مجموع التقرير مقابل مجموع السجلات المصدرية (تدقيق §16.4-G).
    final sourceExpensesTotal = expenses
        .where((e) => SalaryExpenseClassifier.isSalaryRelated(e.expenseType))
        .fold<double>(0, (s, e) => s + e.amount);
    final directWithdrawalsTotal = withdrawals
        .where(
          (w) =>
              ((w.expenseUuid ?? '').trim().isEmpty ||
              !expenseUuidSet.contains((w.expenseUuid ?? '').trim())),
        )
        .fold<double>(0, (s, w) => s + w.amount);
    final reportTotal = perEmployee.values.fold<double>(
      0,
      (s, r) => s + r.grandTotal,
    );
    final unlinkedTotal = sourceExpensesTotal + directWithdrawalsTotal;

    final rows = perEmployee.values.toList()
      ..sort((a, b) => a.employeeUuid.compareTo(b.employeeUuid));

    return EmployeeTotalsReport(
      rows: rows,
      reportTotal: reportTotal,
      sourceTotal: sourceExpensesTotal + directWithdrawalsTotal,
      reconciliation:
          'مجموع التقرير ($reportTotal) مقابل مجموع المصادر بعد الاستبعاد '
          '($unlinkedTotal) — الفرق = سجلات غير مرتبطة/بلا موظف محلول '
          '(§16.4-G: تظهر في تقرير غير مرتبط ولا تُنسب).',
      totalMovements: movementsCount,
    );
  }
}

