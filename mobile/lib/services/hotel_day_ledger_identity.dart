//
//  الجدول **مشتق** (مجاميع يومية تُبنى من الليالي/الدفعات/المصروفات/
//  المديونيات)، ومصادره الأصلية هي نفسها المُزامَنة عبر المزوّد
//  (bookings / payments / expenses / debts / rooms). لذلك يبقى محلياً بلا
//  مزامنة — **بشرط** أن يكون بناؤه حتمياً غير مُدمِّر. هذا الملف هو مصدر
//  الحقيقة الوحيد لهذا الشرط، ويُستعمل من:
//    • NightAuditService        — الكاتب الحقيقي عند إقفال اليوم.
//    • RestoreFixService        — إعادة البناء بعد الاستعادة/الإصلاح.
//    • AppDatabase (onUpgrade/onOpen) — توحيد الهوية على القواعد القائمة.
//
//  1) الهوية حتمية: `local_uuid = 'ldg-' + hotel_day_key (بلا شرطات)`.
//     الصيغة القديمة `${millisecondsSinceEpoch}-${hash}` كانت تُنتج معرّفاً
//     جديداً في كل إنشاء، ثم تُبدَّل مجدداً مع كل إعادة بناء بعد الاستعادة
//     (حذف الكل + IdGen.uuid) ⇒ هوية غير ثابتة. الهوية الحتمية تجعل نفس
//     اليوم يحمل نفس المعرّف على أي جهاز/استعادة/نسخة احتياطية.
//
//  2) الحالة `closed` (= أقفل Night Audit وأُرسل تقريره) هي **القيمة الوحيدة
//     ذات الدلالة**: `NightAuditService.isDayClosed` لا تعتبر اليوم مُقفلاً
//     بغيرها. إعادة البناء كانت تكتب 'finalized'/'draft' فتُعيد فتح يوم
//     مُقفل بعد أي استعادة.
//
//  3) الصفوف المغلقة سجل تاريخي حقيقي (مجاميعها محسوبة بمنطق الإقفال لا
//     بمنطق إعادة البناء) ⇒ لا تُحذف ولا تُكتب فوقها المجاميع.
// ═══════════════════════════════════════════════════════════════════════════

/// هوية دفتر اليوم الفندقي — ثوابت ومعرّفات حتمية.
class HotelDayLedgerIdentity {
  const HotelDayLedgerIdentity._();

  /// اليوم مُقفل من Night Audit (أُرسل تقريره) — الحالة الوحيدة المقروءة.
  static const String statusClosed = 'closed';

  /// حالة افتراضية في المخطط (صف قديم لم يُقفل ولم يُعَد بناؤه).
  static const String statusDraft = 'draft';

  /// صف مُشتق أنشأته إعادة البناء بعد الاستعادة — لا يعني إقفالاً.
  static const String statusRebuilt = 'rebuilt';

  /// معرّف حتمي ثابت لصف الدفتر: نفس `hotelDayKey` ⇒ نفس المعرّف دائماً.
  ///
  /// ملاحظة إلزامية: قاعدة التنظيف هنا (`replaceAll('-', '')`) مطابقة حرفياً
  /// لـ [legacyUuidNormalizeSql] (SQL) — أي تغيير هنا يجب أن يقابله تغيير هناك
  /// وإلا تباعدت الصيغتان (اختبار القفل في
  /// `test/unit/hotel_day_ledger_restore_identity_test.dart` يحرس التطابق).
  static String deterministicUuid(String hotelDayKey) =>
      'ldg-${hotelDayKey.replaceAll('-', '')}';

  /// توحيد المعرّفات القديمة `${millis}-${hashDigits}` إلى الصيغة الحتمية.
  ///
  /// آمن للتنفيذ المتكرر (idempotent): الصفوف التي تحمل الصيغة الحتمية سلفاً
  /// لا تطابق شرط `NOT LIKE 'ldg-%'`. ولا يُغيَّر أي عمود آخر إطلاقاً
  /// (لا مجاميع ولا حالة ولا تواريخ) — نقل صيغة معرّف فقط، والجدول بلا أي
  /// مرجع خارجي إليه من جداول أخرى (تحقق: لا وجود لِـ ledger_uuid في المخطط).
  ///
  /// لا تخمين: أي معرّف لا يطابق شكل الصيغة القديمة (يبدأ بحرف مثلاً، أو
  /// صيغة uuid عادية) يُترك كما هو.
  static const String legacyUuidNormalizeSql =
      "UPDATE hotel_day_ledger "
      "SET local_uuid = 'ldg-' || replace(hotel_day_key, '-', '') "
      "WHERE local_uuid NOT LIKE 'ldg-%' "
      "AND local_uuid GLOB '[0-9]*-[0-9]*'";

  /// هل المعرّف بالصيغة القديمة غير الحتمية `${millis}-${hash}`؟
  static bool isLegacyUuid(String uuid) {
    if (uuid.startsWith('ldg-')) return false;
    return RegExp(r'^\d+-\d+$').hasMatch(uuid);
  }
}
